export function buildMockNetPremTicks(ticker: string, now = new Date()): NetPremTick[] {
  const tides = buildMockTickerTides();
  const tide = tides[ticker] ?? tideFromPremiums(80_000, 40_000, null);
  const ticks: NetPremTick[] = [];
  for (let i = 30; i >= 0; i -= 1) {
    const t = new Date(now.getTime() - i * 60_000);
    const progress = (30 - i) / 30;
    const jitter = Math.sin(i / 3) * 0.08;
    ticks.push({
      date: t.toISOString().slice(0, 10),
      tape_time: t.toISOString(),
      net_call_premium: String(Math.round(tide.netCallPremium * (0.4 + progress * 0.6 + jitter))),
      net_put_premium: String(Math.round(tide.netPutPremium * (0.4 + progress * 0.6 - jitter))),
      net_call_volume: Math.round(400 + progress * 800),
      net_put_volume: Math.round(200 + progress * 350),
    });
  }
  return ticks;
}
