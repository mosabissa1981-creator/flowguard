function isoDate(offsetDays: number, now = new Date()): string {
  const d = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  d.setUTCDate(d.getUTCDate() + offsetDays);
  return d.toISOString().slice(0, 10);
}

function minutesAgo(mins: number, now = new Date()): string {
  return new Date(now.getTime() - mins * 60_000).toISOString();
}

function chain(ticker: string, expiry: string, type: "call" | "put", strike: number): string {
  const y = expiry.slice(2, 4);
  const m = expiry.slice(5, 7);
  const d = expiry.slice(8, 10);
  const side = type === "call" ? "C" : "P";
  const strikeCode = Math.round(strike * 1000).toString().padStart(8, "0");
  return `${ticker}${y}${m}${d}${side}${strikeCode}`;
}

function alert(partial: Omit<FlowAlert, "option_chain"> & { option_chain?: string }): FlowAlert {
  return {
    ...partial,
    option_chain:
      partial.option_chain ??
      chain(partial.ticker, partial.expiry, partial.type, Number(partial.strike)),
  };
}

